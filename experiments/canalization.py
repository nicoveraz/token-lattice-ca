# ------------------------------------------------------------------ the three quantities

def context_stats(p_base, p_a, p_b, p_ab):
    """Per-context sensitivity, its two-flip response, and the independence prediction.

    s_a, s_b are the exact CRN disagreement probabilities for flipping window position 0 or 1;
    s_ab is the same for flipping both. If the two positions reached the output independently,
    the chance of the draw surviving both flips would be (1-s_a)(1-s_b), so independence predicts
    s_ab = 1 - (1-s_a)(1-s_b). What is measured instead is the whole point.
    """
    s_a, s_b, s_ab = s_crn(p_base, p_a), s_crn(p_base, p_b), s_crn(p_base, p_ab)
    indep = 1.0 - (1.0 - s_a) * (1.0 - s_b)
    return dict(s_a=s_a, s_b=s_b, s=0.5 * (s_a + s_b), s_ab=s_ab,
                indep=indep, subadd=indep - s_ab)


def summarise(ctxs, rng, boot=BOOT):
    """Means, the across-context SPREAD, its bootstrap CI, and the entropy-residualised spread."""
    s = np.array([c["s"] for c in ctxs])
    sub = np.array([c["subadd"] for c in ctxs])
    H = np.array([c["H"] for c in ctxs])
    # CONFOUND CONTROL: a peakier conditional is insensitive for reasons that have nothing to do
    # with masking, so regress sensitivity on entropy and keep the spread of what is left over.
    if np.std(H) > 1e-12:
        beta = np.polyfit(H, s, 1)
        resid_spread = float(np.std(s - np.polyval(beta, H)))
        rho_sH = float(np.corrcoef(s, H)[0, 1])
    else:
        resid_spread, rho_sH = float(np.std(s)), 0.0
    # CLUSTER BOOTSTRAP over distinct context identities. Occupancy weighting is kept (the
    # dynamics see the ring's actual distribution), but the resampling unit is the distinct
    # window, because that is the unit the information comes in. On a degenerate early ring this
    # widens the CI by roughly sqrt(n / n_distinct), which is the correction that was missing.
    keys = [c.get("key", i) for i, c in enumerate(ctxs)]
    uniq = sorted(set(keys))
    groups = {u: np.where(np.array(keys) == u)[0] for u in uniq}
    gi = rng.integers(0, len(uniq), size=(boot, len(uniq)))
    idx = np.array([np.concatenate([groups[uniq[j]] for j in row]) for row in gi], dtype=object) \
        if False else None
    b_spread, b_sub = [], []
    for row in gi:
        sel = np.concatenate([groups[uniq[j]] for j in row])
        b_spread.append(np.std(s[sel])); b_sub.append(sub[sel].mean())
    b_spread = np.array(b_spread); b_sub = np.array(b_sub)
    lo, hi = np.percentile(b_spread, [2.5, 97.5])
    slo, shi = np.percentile(b_sub, [2.5, 97.5])
    return dict(n=len(s), s=round(float(s.mean()), 5), entropy_sd=round(float(H.std()), 4),
                spread=round(float(s.std()), 5),
                spread_ci=[round(float(lo), 5), round(float(hi), 5)],
                spread_resid=round(resid_spread, 5), rho_s_entropy=round(rho_sH, 4),
                subadd=round(float(sub.mean()), 5),
                subadd_ci=[round(float(slo), 5), round(float(shi), 5)],
                s_ab=round(float(np.mean([c["s_ab"] for c in ctxs])), 5),
                indep=round(float(np.mean([c["indep"] for c in ctxs])), 5),
                entropy=round(float(H.mean()), 4))


# ---------------------------------------------------------------- rung 1: DK, analytic

def rung_dk():
    """The p2=0 line is a PURE CANCELLATION anchor: zero spread, maximal sub-additivity.

    DK emits 1 with probability 0 (no parent on), p1 (one on), p2 (both on). On the w18 line p2=0.
    For a Bernoulli pair under a shared uniform the CRN disagreement is |p - q|, so:
      flip one parent, other OFF:  0  <-> p1   -> s = p1
      flip one parent, other ON:   p1 <-> p2=0 -> s = p1
    s is p1 in EVERY context, so the spread is exactly zero -- there is no masking here at all.
      flip BOTH parents: (0,0)<->(1,1) gives 0 <-> p2 = 0, and (0,1)<->(1,0) gives p1 <-> p1,
      so s_ab = 0 in every context: the second flip exactly undoes the first.
    Independence would have predicted 1-(1-p1)^2, so subadd is maximal. This is the same signature
    XOR has, and it is why the pair (spread, subadd) is needed rather than subadd alone.
    """
    from dk import ANCHORS
    out = {}
    for k in (a for a in ANCHORS if "w18" in a):
        p1, p2 = ANCHORS[k]["p1"], ANCHORS[k]["p2"]
        cfgs = [(0, 0), (0, 1), (1, 0), (1, 1)]
        emit = lambda c: (0.0, p1, p2)[c[0] + c[1]]
        s_ctx, sub_ctx = [], []
        for c in cfgs:
            fa = (1 - c[0], c[1])
            fb = (c[0], 1 - c[1])
            fab = (1 - c[0], 1 - c[1])
            s_a, s_b = abs(emit(c) - emit(fa)), abs(emit(c) - emit(fb))
            s_ab = abs(emit(c) - emit(fab))
            s_ctx.append(0.5 * (s_a + s_b))
            sub_ctx.append(1 - (1 - s_a) * (1 - s_b) - s_ab)
        out[k] = dict(p1=p1, p2=p2, s=round(float(np.mean(s_ctx)), 5),
                      spread=round(float(np.std(s_ctx)), 6),
                      subadd=round(float(np.mean(sub_ctx)), 5))
    return dict(anchors=out, expect_spread=0.0,
                reading="on the p2=0 line sensitivity is p1 in every context, so spread is exactly "
                        "zero, while flipping both parents restores the emission probability, so "
                        "sub-additivity is maximal. A cancellation anchor with no masking -- the "
                        "signature the pair must not confuse with canalization.")


