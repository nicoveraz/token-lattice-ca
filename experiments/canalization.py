def rung_eca():
    """Exact enumeration over all 8 neighbourhoods for each rule of known class (F36).

    Deterministic rules make every per-context sensitivity 0 or 1, so independence reduces to OR
    and the measured s_ab is the rule table read directly. No estimation anywhere.
    """
    try:
        eca = json.load(open(_ROOT / "results" / "eca_ordered_vs_rest.json"))
    except FileNotFoundError:
        return None
    classes = {int(rl): grp
               for grp in ("ordered", "edge", "chaotic")
               for rl in eca.get("groups", {}).get(grp, {}).get("rules", {})}
    if not classes:
        return dict(skipped="rule->class mapping not present in eca_ordered_vs_rest.json")
    rows = {}
    for rule, grp in sorted(classes.items()):
        bits = [(rule >> i) & 1 for i in range(8)]
        s_ctx, sub_ctx = [], []
        for cfg in range(8):
            singles = [float(bits[cfg] != bits[cfg ^ (1 << b)]) for b in range(3)]
            s_ctx.append(float(np.mean(singles)))
            for i, j in combinations(range(3), 2):
                s_ab = float(bits[cfg] != bits[cfg ^ (1 << i) ^ (1 << j)])
                sub_ctx.append(1 - (1 - singles[i]) * (1 - singles[j]) - s_ab)
        rows[rule] = dict(group=grp, s=round(float(np.mean(s_ctx)), 4),
                          spread=round(float(np.std(s_ctx)), 4),
                          subadd=round(float(np.mean(sub_ctx)), 4))
    gate = None
    if MASKING_RULE in rows and CANCEL_RULE in rows:
        m, c = rows[MASKING_RULE], rows[CANCEL_RULE]
        passes = bool(m["spread"] > c["spread"] and m["subadd"] > 0 and c["subadd"] > 0)
        gate = dict(masking_rule=MASKING_RULE, cancel_rule=CANCEL_RULE,
                    masking_spread=m["spread"], cancel_spread=c["spread"],
                    masking_subadd=m["subadd"], cancel_subadd=c["subadd"], passes=passes,
                    reading="both rules must be sub-additive while only majority carries spread; "
                            "if XOR shows spread or majority does not, the pair does not separate "
                            "masking from cancellation and rung 3 is NOT read.")
    return dict(rules=rows, n=len(rows), gate=gate)


